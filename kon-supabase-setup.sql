create policy "kon images insert" on storage.objects for insert to authenticated with check (bucket_id = 'kon-images' and public.is_admin());
create policy "kon images update" on storage.objects for update to authenticated using (bucket_id = 'kon-images' and public.is_admin());
create policy "kon images delete" on storage.objects for delete to authenticated using (bucket_id = 'kon-images' and public.is_admin());

