-- مهم: غيّري الإيميل في الدالة التالية إلى إيميل الأدمن الذي ستنشئينه في Authentication > Users.

create or replace function public.is_admin() returns boolean
language sql stable set search_path = '' as $$
  select lower(coalesce(auth.jwt() ->> 'email','')) = lower('youssef20078y@gmail.com');
$$;

create table if not exists public.site_config (
  id int primary key default 1 check (id = 1),
  name text not null default 'كن رياضي' check (char_length(name) <= 60),
  wa text not null default '' check (wa ~ '^[0-9]{0,15}$'),
  sched text not null default '' check (char_length(sched) <= 3000),
  wk jsonb not null default '[]'::jsonb
);
create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null default '' check (char_length(title) <= 120),
  title_en text not null default '' check (char_length(title_en) <= 120),
  image_url text not null,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);
create table if not exists public.challenges (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  target int not null default 1 check (target > 0),
  unit text not null default '' check (char_length(unit) <= 30),
  step int not null default 1 check (step > 0),
  pts int not null default 50 check (pts >= 0),
  sort_order int not null default 0
);
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  emoji text not null default '🏅' check (char_length(emoji) <= 8),
  minutes int not null default 30 check (minutes > 0),
  kcal int not null default 200 check (kcal >= 0),
  sort_order int not null default 0
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  body text not null default '' check (char_length(body) <= 500),
  created_at timestamptz not null default now()
);

do $$ declare t text; begin
  foreach t in array array['site_config','gallery','challenges','games','notifications'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "read" on public.%I', t);
    execute format('drop policy if exists "admin insert" on public.%I', t);
    execute format('drop policy if exists "admin update" on public.%I', t);
    execute format('drop policy if exists "admin delete" on public.%I', t);
    execute format('create policy "read" on public.%I for select using (true)', t);
    execute format('create policy "admin insert" on public.%I for insert to authenticated with check (public.is_admin())', t);
    execute format('create policy "admin update" on public.%I for update to authenticated using (public.is_admin()) with check (public.is_admin())', t);
    execute format('create policy "admin delete" on public.%I for delete to authenticated using (public.is_admin())', t);
  end loop;
end $$;

